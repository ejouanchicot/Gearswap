"""Build the Reive / Incursion capes table: gear/reive.js.

Source: reive_source.json (BG-Wiki "JSE Capes", Reive and Incursion Capes, given by the player on 2026-11-09): one cape
a job, the four augments a Refractive Crystal can give it. The four can be on one cape (the PLD template's Weard Mantle
carries VIT, DEX, Enmity and Phalanx: _master/sets/pld_sets.lua), and an augment's "max" is the highest value it can
reach, so every augment is written at its max. The source's notes (a value the wiki marks "Question", a unit or a sign
it supposes) are kept as they are.

Every augment is written as the game shows it (augment_labels.py), then every line must be read by the optimizer's
augment reader (augments_parse.js) as its stats at that value: reive_check.js, run at the end.

    python reive_build.py
"""
import json, os, subprocess, sys

from augment_labels import LABELS, game_text

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    src = json.load(open(os.path.join(HERE, 'reive_source.json'), encoding='utf-8'))
    items = json.load(open(os.path.join(HERE, 'items.json'), encoding='utf-8'))['items']
    names = set()
    for it in items:
        names.update([it['name'], it.get('enl')])
    capes, check = {}, []
    for c in src['capes']:
        if c['name'] not in names:
            sys.exit('the cape "%s" is not in the catalogue' % c['name'])
        augs, notes = {}, []
        for a in c['augments']:
            txt = game_text(a)
            augs[a['stat']] = [txt]
            check.append({'text': txt, 'value': a['max'], 'parts': len(LABELS[a['stat']]), 'stat': a['stat']})
            if a.get('note'):
                notes.append(txt)
        capes[c['name']] = {'job': c['job'].lower(), 'groups': [a['stat'] for a in c['augments']], 'augs': augs, 'noted': notes}
    js = ('// Generated by atelier/gear/reive_build.py from reive_source.json. Do not edit.\n'
          '// FFXI.REIVE_BY_NAME[cape name] = {job, groups: [its four augments\' stats], augs: {stat: [the augment at its max,\n'
          '// as the game writes it]}, noted: [augments the source has a doubt or a supposition on]};\n'
          '// FFXI.reive_max(name, augs): a cape with each of its augments at its max.\n'
          '// @author ejouanchicot\n'
          '(globalThis.FFXI_PARTS = globalThis.FFXI_PARTS || []).push(function (FFXI) {\n'
          '    var DATA = ' + json.dumps(capes, ensure_ascii=False, separators=(',', ':')) + ';\n'
          + open(os.path.join(HERE, 'reive_tail.js'), encoding='utf-8').read() + '});\n')
    open(os.path.join(HERE, 'reive.js'), 'w', encoding='utf-8', newline='\n').write(js)
    os.makedirs(os.path.join(HERE, 'cache'), exist_ok=True)
    json.dump(check, open(os.path.join(HERE, 'cache', 'reive_check.json'), 'w', encoding='utf-8'), ensure_ascii=False)
    print('reive.js: %d capes, %d augments' % (len(capes), len(check)))
    r = subprocess.run(['node', os.path.join(HERE, 'reive_check.js')])
    sys.exit(r.returncode)


if __name__ == '__main__':
    main()
