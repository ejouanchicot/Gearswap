---============================================================================
--- PATH_RANK_GEAR - Stats of path/rank upgraded equipment, per path and rank
---============================================================================
--- Windower's extdata decode gives only `path` and `rank` for items upgraded
--- along a path (Odyssey gear, Unity +1 gear, JSE necks +2, REMA 119 III
--- weapons...), not the stats those give. This table is that missing piece.
---
--- Built from BG-Wiki (https://www.bg-wiki.com/ffxi/<Item_Name>) on 2026-09-30
--- by reading each item's page. Every value is exactly as the page shows it:
--- nothing is guessed, nothing is recomputed, the page wording is kept even
--- when two parts of the same page word the same stat differently. When a page
--- does not show something, the entry does not have it and `note` says so.
---
--- Entry layout (key = the item's LONG English name, lower case):
---   short   = game short name (lower case), only when it differs from the key
---   kind    = 'odyssey' | 'jse_neck' | 'unity' | 'relic' | 'mythic'
---             | 'empyrean' | 'aeonic' | 'ergon' | 'other'
---   ranked  = true when the page documents stats that change with path/rank
---   source  = the BG-Wiki page read
---   base    = { the page's item description line, verbatim, unsplit }
---             (the stats before any path/rank augment)
---   paths   = only the paths the page shows. A page that names no path
---             letter is stored under 'unspecified'.
---     max_rank = the max rank the page gives
---     at_max   = the page's max-rank summary box, one string per entry
---     by_rank  = the page's per-rank table, every rank it lists, as it lists
---                them (the tables start at rank 1: no rank 0 row is shown).
---                Empty augment slots ('-----') are left out.
---   note    = anything the page says that does not fit the layout above
---
--- Adding an item: open its BG-Wiki page, copy the description line into
--- `base`, the max-rank box into `at_max` and, if the page has the per-rank
--- table ("Click [Show]"), every row into `by_rank`. Keep the page's wording.
--- Weapons with a disambiguation page (Relic/Mythic/Empyrean): read the
--- "(Level 119 III)" version page.
---
