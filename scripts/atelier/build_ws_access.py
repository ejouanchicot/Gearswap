"""Which weapon each weaponskill belongs to and which job has it, for the Atelier page's Configuration tab.

The page lets a player fill the weaponskill slots of each weapon (<JOB>_WS_CONFIG.lua, //gs c ws1...) by
picking in a window instead of typing a name: the weaponskills of the weapon's kind that the job has first.
This writes the table it reads, atelier/app/js/ws_access_data.js:

  WS_ACCESS  {weaponskill: [combat skill, {JOB: level} or null]}

The combat skill ("Sword", "Great Axe") is the game's own (Windower res/weapon_skills.lua and res/skills.lua);
the jobs and levels are the project's weaponskill databases (shared/data/weaponskills/*_WS_DATABASE.lua, checked
against BG-Wiki). A weaponskill the databases do not hold (Marksmanship) has null: the page then shows it for
its weapon without telling the jobs apart.

Run from data/ after a weaponskill database changed or after a game update:
  python scripts/atelier/build_ws_access.py

@author ejouanchicot
"""
import glob
import json
import os
import re
import sys

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')

DATA = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
RES = os.path.normpath(os.path.join(DATA, '..', '..', '..', 'res'))
OUT = os.path.join(DATA, 'atelier', 'app', 'js', 'ws_access_data.js')

HEADER = re.compile(r"""^\s*\[\s*(['"])((?:\\.|(?!\1).)+)\1\s*\]\s*=\s*\{""", re.M)
JOBS = re.compile(r'\b(?:jobs|job_levels)\s*=\s*\{([^{}]*)\}')
PAIR = re.compile(r'\b([A-Z]{3})\s*=\s*(\d+)')


def read(path):
    return open(path, encoding='utf-8', errors='replace').read()


def game_skills():
    """{weaponskill: combat skill name} from Windower's resources."""
    skills = dict((int(i), n) for i, n in re.findall(r'\[(\d+)\]\s*=\s*\{id=\d+,en="([^"]+)"', read(os.path.join(RES, 'skills.lua'))))
    out = {}
    for name, skill in re.findall(r'\{id=\d+,en="([^"]+)".*?\bskill=(\d+)', read(os.path.join(RES, 'weapon_skills.lua'))):
        out[name] = skills.get(int(skill), '')
    return out


def database_jobs():
    """{weaponskill: {JOB: level}} from the project's weaponskill databases."""
    out = {}
    for path in sorted(glob.glob(os.path.join(DATA, 'shared', 'data', 'weaponskills', '*_WS_DATABASE.lua'))):
        text = re.sub(r'--[^\n]*', '', read(path))
        heads = list(HEADER.finditer(text))
        for i, head in enumerate(heads):
            body = text[head.end():heads[i + 1].start() if i + 1 < len(heads) else len(text)]
            jobs = JOBS.search(body)
            if jobs:
                name = head.group(2).replace("\\'", "'").replace('\\"', '"')
                out[name] = dict((j, int(lv)) for j, lv in PAIR.findall(jobs.group(1)))
    return out


def main():
    skills, jobs = game_skills(), database_jobs()
    table = dict((name, [skill, jobs.get(name)]) for name, skill in sorted(skills.items()) if skill)
    unknown = sorted(n for n in jobs if n not in skills)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// GENERATED by scripts/atelier/build_ws_access.py: do not edit. Each weaponskill\'s combat skill (Windower\n'
                '// res/weapon_skills.lua) and the jobs that have it with their level (shared/data/weaponskills/), null when\n'
                '// the databases do not hold it. Read by module_ux.js to offer a weapon\'s weaponskills.\n'
                'const WS_ACCESS = ' + json.dumps(table, ensure_ascii=False, separators=(',', ':')) + ';\n')
    with_jobs = sum(1 for v in table.values() if v[1])
    print('%d weaponskills, %d with their jobs -> %s' % (len(table), with_jobs, os.path.relpath(OUT, DATA)))
    if unknown:
        print('in the databases but not in the game\'s resources (a name to check): ' + ', '.join(unknown))


if __name__ == '__main__':
    main()
