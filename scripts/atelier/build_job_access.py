"""Which job has which ability and which spell, for the Atelier page's list of sets.

The page shows a job's sets only when the job, or the subjob chosen, can use what the set is for
(sets.precast.JA.Jump with a WAR/SAM: hidden; with a WAR/DRG: shown). This writes the table it reads,
atelier/app/js/job_access_data.js:

  JA_ACCESS    {ability: [[JOB, level, main job only (1/0)], ...]}   from shared/data/job_abilities/<job>/*.lua
  SPELL_ACCESS {spell: {JOB: level}}                                 from Windower's res/spells.lua
  SPELL_SKILL  {spell: its magic skill}                              from res/spells.lua and res/skills.lua

Run from data/ after an ability was added to a job's database or after a game update:
  python scripts/atelier/build_job_access.py

@author ejouanchicot
"""
import glob
import json
import os
import re
import sys

DATA = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
RES = os.path.normpath(os.path.join(DATA, '..', '..', '..', 'res'))
OUT = os.path.join(DATA, 'atelier', 'app', 'js', 'job_access_data.js')

ENTRY = re.compile(r"""\[\s*(['"])(.+?)\1\s*\]\s*=\s*\{([^{}]*)\}""", re.S)


def abilities():
    """{name: [[JOB, level, main only], ...]} from the job ability databases."""
    out = {}
    for path in sorted(glob.glob(os.path.join(DATA, 'shared', 'data', 'job_abilities', '*', '*.lua'))):
        job = os.path.basename(os.path.dirname(path)).upper()
        stem = os.path.basename(path)[:-4]
        # a file of the main job's own abilities, or of its SP abilities: never a subjob's
        file_main = stem.endswith('_mainjob') or stem.endswith('_sp')
        text = open(path, encoding='utf-8', errors='replace').read()
        for _, name, body in ENTRY.findall(text):
            level = re.search(r'\blevel\s*=\s*(\d+)', body)
            if not level:
                continue
            flag = re.search(r'\bmain_job_only\s*=\s*(true|false)', body)
            main_only = file_main or bool(flag and flag.group(1) == 'true')
            row = [job, int(level.group(1)), 1 if main_only else 0]
            if row not in out.setdefault(name.replace("\\'", "'"), []):
                out[name.replace("\\'", "'")].append(row)
    return out


def lua_rows(path):
    """The rows of a Windower resource file, one a line: {field: text}."""
    for line in open(path, encoding='utf-8', errors='replace'):
        if re.match(r'\s*\[\d+\]\s*=\s*\{', line):
            yield line


def spells():
    jobs = {int(m.group(1)): m.group(2) for line in lua_rows(os.path.join(RES, 'jobs.lua'))
            for m in [re.search(r'id=(\d+),.*?ens="(\w+)"', line)] if m}
    skills = {int(m.group(1)): m.group(2) for line in lua_rows(os.path.join(RES, 'skills.lua'))
              for m in [re.search(r'id=(\d+),en="([^"]+)"', line)] if m}
    access, skill = {}, {}
    for line in lua_rows(os.path.join(RES, 'spells.lua')):
        name = re.search(r'\ben="([^"]+)"', line)
        levels = re.search(r'levels=\{([^}]*)\}', line)
        if not name or not levels or not levels.group(1).strip():
            continue
        by_job = {jobs[int(j)]: int(lv) for j, lv in re.findall(r'\[(\d+)\]=(\d+)', levels.group(1)) if int(j) in jobs}
        if not by_job:
            continue
        # two spells of one name (a Trust and a spell...): the levels of both
        access.setdefault(name.group(1), {}).update(by_job)
        sk = re.search(r'\bskill=(\d+)', line)
        if sk and int(sk.group(1)) in skills:
            skill[name.group(1)] = skills[int(sk.group(1))]
    return access, skill


def main():
    if not os.path.isfile(os.path.join(RES, 'spells.lua')):
        sys.exit('Windower resources not found: ' + RES)
    ja = abilities()
    access, skill = spells()
    dump = lambda v: json.dumps(v, ensure_ascii=False, separators=(',', ':'), sort_keys=True)
    text = ('// GENERATED by scripts/atelier/build_job_access.py: do not edit. Which job has which ability (the job\n'
            '// ability databases of shared/data/job_abilities) and which spell (Windower res/spells.lua), read by\n'
            '// job_access.js to show a job only the sets it can use.\n'
            'const JA_ACCESS = ' + dump(ja) + ';\n'
            'const SPELL_ACCESS = ' + dump(access) + ';\n'
            'const SPELL_SKILL = ' + dump(skill) + ';\n')
    open(OUT, 'w', encoding='utf-8', newline='\n').write(text)
    print('%d abilities of %d jobs, %d spells -> %s (%d KB)' % (len(ja), len({r[0] for v in ja.values() for r in v}), len(access),
                                                               os.path.relpath(OUT, DATA), len(text) // 1024))


if __name__ == '__main__':
    main()
