"""The game's usable items (medicine, food, tools, scrolls...), for the Atelier page's settings.

The Modules part of the page shows the item lists of the settings files (the items against a debuff,
the items the refill never puts back) with the game's own icons, and offers every usable item to add.
The gear catalog (atelier/catalog.js) only holds equipment; this writes the usable ones,
atelier/app/js/usables_data.js:

  USABLE_ITEMS  [[id, name], ...]   every item of category "Usable" in Windower's res/items.lua

Run from data/ after a game update:
  python scripts/atelier/build_usables.py

@author ejouanchicot
"""
import json
import os
import re

DATA = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
RES = os.path.normpath(os.path.join(DATA, '..', '..', '..', 'res'))
OUT = os.path.join(DATA, 'atelier', 'app', 'js', 'usables_data.js')

ITEM = re.compile(r'\[(\d+)\] = \{id=\d+,en="((?:[^"\\]|\\.)*)"[^\n]*category="Usable"')


def main():
    text = open(os.path.join(RES, 'items.lua'), encoding='utf-8').read()
    items = sorted(((int(m.group(1)), m.group(2).replace('\\"', '"')) for m in ITEM.finditer(text)), key=lambda x: (x[1].lower(), x[0]))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// GearSwap Atelier · usables_data.js: the game\'s usable items, [id, name], by name.\n'
                '// Generated by scripts/atelier/build_usables.py from Windower\'s res/items.lua: do not edit, run it again.\n'
                'const USABLE_ITEMS = ' + json.dumps(items, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print('%d usable items -> %s' % (len(items), os.path.relpath(OUT, DATA)))


if __name__ == '__main__':
    main()
