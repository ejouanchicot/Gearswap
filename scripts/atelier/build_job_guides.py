"""What this GearSwap does on each job, in English, for the Atelier page's Modules part.

The page opens its Modules part on a presentation of the job shown: how the job is set up and what
it does by itself. The English of it is the "Overview" of each job's page of the player docs
(docs/user/jobs/<job>/README.md), so the two cannot drift apart; the French is written by hand in
atelier/app/js/job_guide_fr.js. This writes atelier/app/js/job_guide_data.js:

  JOB_GUIDE_EN  {JOB: [intro, [[title, text], ...]]}

Run from data/ after a job's README changed:
  python scripts/atelier/build_job_guides.py

@author ejouanchicot
"""
import json
import os
import re

DATA = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
JOBS = os.path.join(DATA, 'docs', 'user', 'jobs')
OUT = os.path.join(DATA, 'atelier', 'app', 'js', 'job_guide_data.js')


def plain(text):
    """Markdown to the plain words of a sentence."""
    text = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', text)
    text = text.replace('`', '').replace('**', '')
    return re.sub(r'\s+', ' ', text).strip()


def overview(path):
    lines, on = [], False
    for line in open(path, encoding='utf-8').read().split('\n'):
        if line.startswith('## '):
            on = line.strip() == '## Overview'
            continue
        if on and not line.lstrip().startswith('|'):
            lines.append(line)
    intro, points, cur = [], [], None
    for line in lines:
        if line.startswith('- '):
            cur = [line[2:]]
            points.append(cur)
        elif cur is not None and line.startswith('  '):
            cur.append(line.strip())
        elif line.strip() == '':
            cur = None
        elif not points:
            intro.append(line.strip())
    out = []
    for p in points:
        text = ' '.join(p)
        # "**Title.** text" or "**Title**: text": the bold words are the point's title
        m = re.match(r'\*\*(.+?)\*\*[:.]?\s*(.*)$', text, re.S)
        title, body = (m.group(1).rstrip('.:'), m.group(2)) if m else ('', text)
        out.append([plain(title), plain(body)])
    return [plain(' '.join(intro)), out]


def main():
    guides = {}
    for job in sorted(os.listdir(JOBS)):
        readme = os.path.join(JOBS, job, 'README.md')
        if os.path.isfile(readme):
            guides[job.upper()] = overview(readme)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// GearSwap Atelier · job_guide_data.js: what this GearSwap does on each job, [intro, [[title, text], ...]].\n'
                '// Generated by scripts/atelier/build_job_guides.py from docs/user/jobs/<job>/README.md (Overview): do not edit,\n'
                '// change the job\'s page and run it again. The French is atelier/app/js/job_guide_fr.js.\n'
                'const JOB_GUIDE_EN = ' + json.dumps(guides, ensure_ascii=False, indent=1) + ';\n')
    print('%d jobs -> %s' % (len(guides), os.path.relpath(OUT, DATA)))
    for job, (intro, points) in guides.items():
        print('  %s  %d points%s' % (job, len(points), '' if intro else '  (no intro)'))


if __name__ == '__main__':
    main()
