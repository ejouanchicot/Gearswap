"""What each mode of each job does, in English, for the Atelier page's Configuration tab.

The page explains every mode of the job shown (Modes, Keys and Switches parts). The English of it is
the "What it does" column of the tables of each job's states page of the player docs
(docs/user/jobs/<job>/states.md), so the two cannot drift apart; the French is written by hand in
atelier/app/js/state_help_fr.js. This writes atelier/app/js/state_help_data.js:

  STATE_HELP_EN  {JOB: {State: text}}

A row that covers several states (`WS1` ... `WS5`) gives its text to each of them.

Run from data/ after a job's states page changed:
  python scripts/atelier/build_state_help.py            writes the file
  python scripts/atelier/build_state_help.py --list     also prints every row (to write the French from)

@author ejouanchicot
"""
import json
import os
import re
import sys

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')   # a Windows console is not UTF-8

DATA = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
JOBS = os.path.join(DATA, 'docs', 'user', 'jobs')
OUT = os.path.join(DATA, 'atelier', 'app', 'js', 'state_help_data.js')


def plain(text):
    text = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', text)
    text = text.replace('`', '').replace('**', '').replace('\\|', '/')
    return re.sub(r'\s+', ' ', text).strip()


def cells(line):
    return [c.strip() for c in re.split(r'(?<!\\)\|', line.strip().strip('|'))]


def states_of(cell):
    """The state names a table cell holds: every `Name` in backticks that is a Lua name; `WS1` ... `WS5` is the five."""
    names = re.findall(r'`([A-Za-z][A-Za-z0-9]*)`', cell)
    span = re.search(r'`([A-Za-z]+)(\d+)`\s*(?:…|\.\.\.|-|to)\s*`([A-Za-z]+)(\d+)`', cell)
    if span and span.group(1) == span.group(3):
        names = [span.group(1) + str(i) for i in range(int(span.group(2)), int(span.group(4)) + 1)]
    return names


def rows(path):
    out, header = [], None
    for line in open(path, encoding='utf-8').read().split('\n'):
        if not line.startswith('|'):
            header = None
            continue
        c = cells(line)
        if header is None:
            header = [h.lower() for h in c]
            continue
        if set(line) <= set('|-: '):
            continue
        if not any('what it does' in h for h in header) or not any(h.startswith('mode') for h in header):
            continue
        mode = c[next(i for i, h in enumerate(header) if h.startswith('mode'))]
        what = c[next(i for i, h in enumerate(header) if 'what it does' in h)]
        values = c[next((i for i, h in enumerate(header) if h.startswith('values')), 0)] if any(h.startswith('values') for h in header) else ''
        names = states_of(mode)
        if names:
            out.append((names, plain(mode), plain(values), plain(what)))
    return out


def main():
    table = {}
    for job in sorted(os.listdir(JOBS)):
        page = os.path.join(JOBS, job, 'states.md')
        if not os.path.isfile(page):
            continue
        table[job.upper()] = {}
        for names, mode, values, what in rows(page):
            if '--list' in sys.argv:
                print('%s | %s | %s | %s' % (job.upper(), ','.join(names), values[:70], what))
            for n in names:
                table[job.upper()][n] = what
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// GearSwap Atelier · state_help_data.js: what each mode of each job does, {JOB: {State: text}}.\n'
                '// Generated by scripts/atelier/build_state_help.py from docs/user/jobs/<job>/states.md: do not edit, change the\n'
                '// job\'s page and run it again. The French is atelier/app/js/state_help_fr.js.\n'
                'const STATE_HELP_EN = ' + json.dumps(table, ensure_ascii=False, indent=1) + ';\n')
    print('%d jobs, %d modes -> %s' % (len(table), sum(len(v) for v in table.values()), os.path.relpath(OUT, DATA)), file=sys.stderr)


if __name__ == '__main__':
    main()
