"""The game's long names of the pieces whose short name is cut, for the Atelier page's searches.

The game names a piece in 15 letters or so: "Clr. Torque +2" is the Cleric's Torque +2, "Ebers Pant. +3" the Ebers
Pantaloons +3. A player types the name they know; the page looks in both (atelier/app/js/core.js nameHas). This
writes atelier/app/js/long_names_data.js:

  GEAR_LONG  {short name: long name, lower case}   every piece of Windower's res/items.lua whose long name says
                                                   more than its short one ("pair of" and the like taken out)

Run from data/ after a game update:
  python scripts/atelier/build_long_names.py

@author ejouanchicot
@date   Created: 2026-10-31
"""
import json
import os
import re

DATA = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
RES = os.path.normpath(os.path.join(DATA, '..', '..', '..', 'res'))
OUT = os.path.join(DATA, 'atelier', 'app', 'js', 'long_names_data.js')

ITEM = re.compile(r'\[(\d+)\] = \{id=\d+,en="((?:[^"\\]|\\.)*)",ja="[^"]*",enl="((?:[^"\\]|\\.)*)"([^\n]*)')
# the long name's counting words: "pair of gloves" is the gloves
COUNTED = re.compile(r'^(pairs? of|set of|suit of|piece of) ')


def main():
    text = open(os.path.join(RES, 'items.lua'), encoding='utf-8').read()
    out = {}
    for m in ITEM.finditer(text):
        if 'slots=' not in m.group(4):
            continue
        short, long = m.group(2).replace('\\"', '"'), COUNTED.sub('', m.group(3).replace('\\"', '"').lower())
        if short.lower() != long:
            out[short] = long
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// GearSwap Atelier · long_names_data.js: the long names of the pieces whose short name is cut, {short: long}.\n'
                '// Generated by scripts/atelier/build_long_names.py from Windower\'s res/items.lua: do not edit, run it again.\n'
                'const GEAR_LONG = ' + json.dumps(dict(sorted(out.items())), ensure_ascii=False, separators=(',', ':')) + ';\n')
    print('%d long names -> %s' % (len(out), os.path.relpath(OUT, DATA)))


if __name__ == '__main__':
    main()
